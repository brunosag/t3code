import { useEffect, useSyncExternalStore } from "react";
import { PlayIcon, SquareIcon } from "lucide-react";
import {
  DEFAULT_UNIFIED_SETTINGS,
  READ_ALOUD_VOICES,
  type ReadAloudVoice,
} from "@t3tools/contracts";

import { readAloud } from "~/lib/readAloud";
import { usePrimaryEnvironmentId } from "~/state/environments";
import {
  READ_ALOUD_VOICE_GROUPS,
  READ_ALOUD_VOICE_INFO,
  readAloudVoiceLabel,
  readAloudVoicePreviewText,
} from "@t3tools/client-runtime/read-aloud";
import { Button } from "../ui/button";
import {
  Select,
  SelectGroup,
  SelectGroupLabel,
  SelectItem,
  SelectPopup,
  SelectTrigger,
  SelectValue,
} from "../ui/select";
import { SettingResetButton, SettingsRow } from "./settingsLayout";
import { useSearchableSetting } from "./settingsSearch";
import { useSettingsScope } from "./SettingsScopeContext";
import { useScopedSettings, useUpdateScopedSettings } from "./useScopedSettings";

const PREVIEW_KEY = "settings-voice-preview";
const getServerSnapshot = () => null;

function isReadAloudVoice(value: unknown): value is ReadAloudVoice {
  return READ_ALOUD_VOICES.some((voice) => voice === value);
}

export function ReadAloudVoiceSettings() {
  const setting = useSearchableSetting();
  const voice = useScopedSettings((settings) => settings.readAloudVoice);
  const updateSettings = useUpdateScopedSettings();
  // The preview is generated by the host of the environment being configured.
  const { target } = useSettingsScope();
  const primaryEnvironmentId = usePrimaryEnvironmentId();
  const previewEnvironmentId = target?.environmentId ?? primaryEnvironmentId;
  const preview = useSyncExternalStore(
    readAloud.subscribe,
    () => readAloud.getSnapshot(PREVIEW_KEY),
    getServerSnapshot,
  );
  // oxlint-disable-next-line t3code/no-unreasoned-state-sync -- stops the preview's audio playback on unmount
  useEffect(() => () => readAloud.stopMessage(PREVIEW_KEY), []);

  const previewing = preview !== null && preview.status !== "error" && preview.status !== "ended";
  const info = READ_ALOUD_VOICE_INFO[voice];
  const description =
    preview?.status === "preparing"
      ? `${preview.progress?.label ?? "Preparing preview…"}${
          preview.progress?.percent != null ? ` ${preview.progress.percent}%` : ""
        }`
      : (preview?.error ??
        "Voice used to read responses aloud. Each environment downloads its speech model on first use.");

  return (
    <SettingsRow
      {...setting("read-aloud-voice")}
      description={<span role="status">{description}</span>}
      resetAction={
        voice !== DEFAULT_UNIFIED_SETTINGS.readAloudVoice ? (
          <SettingResetButton
            ariaLabel="Reset read aloud voice to default"
            onClick={() => {
              readAloud.stopMessage(PREVIEW_KEY);
              updateSettings({ readAloudVoice: DEFAULT_UNIFIED_SETTINGS.readAloudVoice });
            }}
          />
        ) : null
      }
      control={
        <div className="flex items-center gap-2">
          <Select
            value={voice}
            onValueChange={(value) => {
              if (!isReadAloudVoice(value)) return;
              readAloud.stopMessage(PREVIEW_KEY);
              updateSettings({ readAloudVoice: value });
            }}
          >
            <SelectTrigger size="sm" className="w-full sm:w-48" aria-label="Read aloud voice">
              <SelectValue>{readAloudVoiceLabel(voice)}</SelectValue>
            </SelectTrigger>
            <SelectPopup align="end" alignItemWithTrigger={false}>
              {READ_ALOUD_VOICE_GROUPS.map((group) => (
                <SelectGroup key={group.label}>
                  <SelectGroupLabel>{group.label}</SelectGroupLabel>
                  {group.voices.map((option) => (
                    <SelectItem key={option} value={option}>
                      {READ_ALOUD_VOICE_INFO[option].name}
                    </SelectItem>
                  ))}
                </SelectGroup>
              ))}
            </SelectPopup>
          </Select>
          <Button
            type="button"
            size="sm"
            variant="outline"
            aria-label={previewing ? "Stop voice preview" : `Preview ${info.name} voice`}
            disabled={!previewing && previewEnvironmentId === null}
            onClick={() => {
              if (previewing) {
                readAloud.stopMessage(PREVIEW_KEY);
                return;
              }
              if (previewEnvironmentId === null) return;
              void readAloud.start(PREVIEW_KEY, {
                environmentId: previewEnvironmentId,
                text: readAloudVoicePreviewText(voice),
                voice,
              });
            }}
          >
            {previewing ? <SquareIcon /> : <PlayIcon />}
            {previewing ? "Stop" : "Preview"}
          </Button>
        </div>
      }
    />
  );
}
