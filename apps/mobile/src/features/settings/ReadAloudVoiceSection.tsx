import { useAtomSet, useAtomValue } from "@effect/atom-react";
import {
  READ_ALOUD_VOICE_GROUPS,
  READ_ALOUD_VOICE_INFO,
  readAloudVoiceLabel,
  readAloudVoicePreviewText,
} from "@t3tools/client-runtime/read-aloud";
import { DEFAULT_UNIFIED_SETTINGS, READ_ALOUD_VOICES } from "@t3tools/contracts";
import { AsyncResult } from "effect/reactivity";
import { useEffect, useSyncExternalStore } from "react";
import { View } from "react-native";

import { ListActionRow } from "../../components/ui/ListActionRow";
import { ListRowLayout } from "../../components/ui/ListRowLayout";
import { Menu } from "../../components/ui/Menu";
import { useEnvironments } from "../../state/environments";
import { mobilePreferencesAtom, updateMobilePreferencesAtom } from "../../state/preferences";
import { readAloud } from "../read-aloud/readAloud";
import { SettingsSection } from "./components/SettingsSection";

const PREVIEW_KEY = "settings-voice-preview";
const getPreview = () => readAloud.getSnapshot(PREVIEW_KEY);

export function ReadAloudVoiceSection() {
  const preferences = useAtomValue(mobilePreferencesAtom);
  const savePreferences = useAtomSet(updateMobilePreferencesAtom);
  const voice =
    (AsyncResult.isSuccess(preferences) ? preferences.value.readAloudVoice : undefined) ??
    DEFAULT_UNIFIED_SETTINGS.readAloudVoice;
  const info = READ_ALOUD_VOICE_INFO[voice];
  // The preview is generated by a connected environment's host, as responses are.
  const { environments } = useEnvironments();
  const previewEnvironment = environments.find(
    (environment) => environment.connection.phase === "connected",
  );
  const preview = useSyncExternalStore(readAloud.subscribe, getPreview);
  // oxlint-disable-next-line t3code/no-unreasoned-state-sync -- stops the preview's audio playback on unmount
  useEffect(() => () => readAloud.stopMessage(PREVIEW_KEY), []);
  const previewing = preview !== null && preview.status !== "error" && preview.status !== "ended";

  return (
    <SettingsSection
      title="Read aloud"
      footer={
        preview?.status === "preparing"
          ? `${preview.progress?.label ?? "Preparing preview…"}${
              preview.progress?.percent != null ? ` ${preview.progress.percent}%` : ""
            }`
          : (preview?.error ??
            "Responses are read aloud by the environment that ran them. Each environment downloads its speech model on first use.")
      }
    >
      <Menu
        title="Voice"
        actions={READ_ALOUD_VOICE_GROUPS.map((group) => ({
          id: group.label,
          title: group.label,
          subactions: group.voices.map((option) => ({
            id: option,
            title: READ_ALOUD_VOICE_INFO[option].name,
            state: option === voice ? "on" : "off",
          })),
        }))}
        onPressAction={({ nativeEvent }) => {
          const next = READ_ALOUD_VOICES.find((option) => option === nativeEvent.event);
          if (!next) return;
          readAloud.stopMessage(PREVIEW_KEY);
          savePreferences({ readAloudVoice: next });
        }}
      >
        <View accessibilityLabel={`Voice, ${readAloudVoiceLabel(voice)}`}>
          <ListRowLayout icon="speaker.wave.2" label="Voice" detail={readAloudVoiceLabel(voice)} />
        </View>
      </Menu>
      <View className="border-t border-border-subtle">
        <ListActionRow
          icon={previewing ? "stop.fill" : "play"}
          label={previewing ? "Stop preview" : `Preview ${info.name}`}
          disabled={!previewing && !previewEnvironment}
          onPress={() => {
            if (previewing) {
              readAloud.stopMessage(PREVIEW_KEY);
              return;
            }
            if (!previewEnvironment) return;
            void readAloud.start(PREVIEW_KEY, {
              environmentId: previewEnvironment.environmentId,
              text: readAloudVoicePreviewText(voice),
              voice,
            });
          }}
        />
      </View>
    </SettingsSection>
  );
}
