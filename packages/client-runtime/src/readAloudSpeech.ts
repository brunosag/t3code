import { SpeechSynthesisError, type SpeechSynthesisEvent, WS_METHODS } from "@t3tools/contracts";
import * as Cause from "effect/Cause";
import * as Effect from "effect/Effect";
import * as Exit from "effect/Exit";
import * as Schema from "effect/Schema";
import * as Stream from "effect/Stream";

import * as EnvironmentRegistry from "./connection/registry.ts";
import type { ReadAloudBackend, SpeechGenerationProgress } from "./readAloudController.ts";
import { runStream } from "./rpc/client.ts";

const isSpeechSynthesisError = Schema.is(SpeechSynthesisError);

function describeProgress(
  event: Extract<SpeechSynthesisEvent, { readonly type: "progress" }>,
): SpeechGenerationProgress {
  const percent = event.total ? Math.round((event.completed / event.total) * 100) : null;
  switch (event.stage) {
    case "wording":
      return { label: "Rewriting for speech…", percent: null, estimatedDuration: null };
    case "downloading-model":
      return { label: "Downloading speech model…", percent, estimatedDuration: null };
    case "starting":
      return { label: "Starting speech…", percent: null, estimatedDuration: null };
    case "generating":
      return {
        label: event.total
          ? `Generating speech (${event.completed + 1} of ${event.total})…`
          : "Generating speech…",
        percent: null,
        estimatedDuration: event.estimatedDurationSeconds ?? null,
      };
  }
}

/**
 * Speech is generated by the environment's host, which streams one WAV file per sentence.
 * `run` executes the stream with the client's connection services.
 */
export function environmentSpeechGenerator(
  run: <E>(
    effect: Effect.Effect<void, E, EnvironmentRegistry.EnvironmentRegistry>,
    signal: AbortSignal,
  ) => Promise<Exit.Exit<void, E>>,
): ReadAloudBackend["generate"] {
  return async (request, signal, onProgress, onChunk) => {
    const exit = await run(
      Effect.gen(function* () {
        const registry = yield* EnvironmentRegistry.EnvironmentRegistry;
        yield* registry
          .runStream(
            request.environmentId,
            runStream(WS_METHODS.speechSynthesize, {
              text: request.text,
              ...(request.markdown === undefined ? {} : { markdown: request.markdown }),
              voice: request.voice,
            }),
          )
          .pipe(
            Stream.runForEach((event) =>
              Effect.sync(() => {
                if (event.type === "chunk") {
                  onChunk({ audio: event.audio, duration: event.durationSeconds });
                } else {
                  onProgress(describeProgress(event));
                }
              }),
            ),
          );
      }),
      signal,
    );
    if (Exit.isSuccess(exit)) return;
    if (signal.aborted) throw new Error("Stopped");
    const error = Cause.squash(exit.cause);
    throw new Error(
      isSpeechSynthesisError(error)
        ? error.message
        : "Couldn't generate speech on this environment. Check that it's connected and up to date.",
    );
  };
}
